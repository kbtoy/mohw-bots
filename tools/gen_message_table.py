"""Generate dll/src/messages.inc (MSG(typeHash, "Name")) from re/messages.json, for the DLL's message trace.

Usage: python -I gen_message_table.py <re/messages.json> <out.inc>
"""
import json
import sys

table = json.load(open(sys.argv[1], encoding="utf-8"))
lines = ["// Generated by tools/gen_message_table.py from re/messages.json - do not edit by hand.",
         "// MSG(type hash at message+0x08, reflected name)"]
for h, info in sorted(table.items(), key=lambda kv: int(kv[0], 16)):
    lines.append(f'MSG({h}u, "{info["name"]}")')
open(sys.argv[2], "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"{len(table)} messages")
